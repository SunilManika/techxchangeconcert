#!/usr/bin/env python3
"""
Upload certificate inventory data to IBM Concert 3.0.x.

This version uses the supported Concert API authentication mechanism:

    Authorization: C_API_KEY <api-key>
    InstanceID: <instance-id>

It intentionally does not use the internal Solis ``handle_login`` endpoint.
That endpoint can issue a Hub token with ``role=User`` in OIDC deployments and
is not the supported authentication path for Concert ingestion automation.

Required environment variables
------------------------------
CONCERT_URL
    Concert URL, for example:
    https://concert-concert.apps.example.com/concert

CONCERT_API_KEY
    API key generated by IBM Concert. The key is never printed.

CONCERT_INSTANCE_ID
    Concert instance ID. If omitted, the script attempts to read it from the
    ``solis-account-instances-cm`` ConfigMap by using the current ``oc`` login.

Environment selection
---------------------
Specify one Concert environment for all rows with either:

    export CONCERT_ENV_NAME=retail-demo

or:

    python3 upload-certificates.py certificate.csv --env-name retail-demo

Alternatively, the input CSV may contain an additional ``Environment`` column.
The certificate ``Namespace`` column is preserved as certificate metadata and
is not automatically treated as the Concert environment.

Optional environment variables
------------------------------
CONCERT_SKIP_TLS=false
    Set to true only for a disposable lab with an untrusted route certificate.

CONCERT_CA_BUNDLE
    Path to a PEM CA bundle. Preferred over CONCERT_SKIP_TLS=true.

CONCERT_REQUEST_TIMEOUT=60
    Per-request timeout in seconds.

CONCERT_POLL_TIMEOUT=300
    Maximum time to wait for uploaded certificate records. A timeout returns
    exit code 2 because the import was accepted but remains unconfirmed.

CONCERT_POLL_INTERVAL=5
    Poll interval in seconds.

CONCERT_HUB_NS=concert-hub
    Namespace used only when discovering the instance ID with ``oc``.

Exit codes
----------
0  Every upload was accepted and all certificate serials were confirmed.
1  Validation, authentication, upload, or verification failed.
2  Every request was accepted, but at least one import remained unconfirmed.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import os
import shutil
import ssl
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, Optional, Sequence, Set, Tuple


UPLOAD_PATH = "/concert/ingestion/api/v1/upload_files"
CERTIFICATES_PATH = "/concert/core/api/v1/certificates"
ENVIRONMENTS_PATH = "/concert/core/api/v1/environments"

CERTIFICATE_REQUIRED_COLUMNS = (
    "Serial Number",
    "Name",
    "Subject",
    "CN",
    "Issuer",
    "ValidFrom",
    "Valid To",
    "Namespace",
)

TRUE_VALUES = {"1", "true", "yes", "on"}


class ConcertError(RuntimeError):
    """Expected validation, configuration, or API failure."""


@dataclass(frozen=True)
class Config:
    base_url: str
    api_key: str
    instance_id: str
    environment_override: str
    hub_namespace: str
    request_timeout: int
    poll_timeout: int
    poll_interval: int
    skip_tls: bool
    ca_bundle: str
    check_environment: bool

    @property
    def authorization_header(self) -> str:
        return f"C_API_KEY {self.api_key}"


@dataclass(frozen=True)
class HttpResult:
    status: int
    body: bytes
    headers: Mapping[str, str]

    @property
    def text(self) -> str:
        return self.body.decode("utf-8", errors="replace")

    def json_or_none(self) -> Any:
        if not self.body:
            return None
        try:
            return json.loads(self.text)
        except json.JSONDecodeError:
            return None


@dataclass
class CsvInput:
    fieldnames: List[str]
    upload_fieldnames: List[str]
    groups: Dict[str, List[Dict[str, str]]]
    serials: Dict[str, Set[str]]
    row_count: int


@dataclass(frozen=True)
class PollResult:
    confirmed: bool
    found: Set[str]
    missing: Set[str]
    last_http_status: int
    fatal_error: str = ""


def env_bool(name: str, default: bool = False) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in TRUE_VALUES


def positive_int(value: str, label: str, allow_zero: bool = False) -> int:
    try:
        parsed = int(value)
    except ValueError as exc:
        raise ConcertError(f"{label} must be an integer; received {value!r}.") from exc
    minimum = 0 if allow_zero else 1
    if parsed < minimum:
        comparison = "zero or greater" if allow_zero else "greater than zero"
        raise ConcertError(f"{label} must be {comparison}; received {parsed}.")
    return parsed


def normalize_base_url(raw_url: str) -> str:
    value = raw_url.strip().rstrip("/")
    if not value:
        raise ConcertError(
            "CONCERT_URL is not set. Example: "
            "export CONCERT_URL=https://concert-concert.apps.example.com/concert"
        )
    parsed = urllib.parse.urlparse(value)
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        raise ConcertError(f"CONCERT_URL is not a valid HTTP(S) URL: {value!r}")
    # Concert's documented API paths begin at /concert. Avoid duplicating a
    # user-supplied /concert path by retaining only scheme and authority here.
    return f"{parsed.scheme}://{parsed.netloc}"


def discover_instance_id(hub_namespace: str) -> str:
    if not shutil.which("oc"):
        return ""

    command = [
        "oc",
        "get",
        "configmap",
        "solis-account-instances-cm",
        "-n",
        hub_namespace,
        "-o",
        "json",
    ]
    try:
        completed = subprocess.run(
            command,
            capture_output=True,
            text=True,
            check=False,
            timeout=20,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ""

    if completed.returncode != 0 or not completed.stdout.strip():
        return ""

    try:
        configmap = json.loads(completed.stdout)
        values = (configmap.get("data") or {}).values()
        for raw_value in values:
            value: Any = raw_value
            # Some installations store a JSON array as a JSON-encoded string.
            for _ in range(2):
                if not isinstance(value, str):
                    break
                try:
                    value = json.loads(value)
                except json.JSONDecodeError:
                    break

            entries = value if isinstance(value, list) else [value]
            for entry in entries:
                if not isinstance(entry, dict):
                    continue
                if entry.get("product_id") == "concert":
                    return str(entry.get("instance_id", "")).strip()
    except (TypeError, ValueError, json.JSONDecodeError):
        return ""

    return ""


def build_config(args: argparse.Namespace) -> Config:
    base_url = normalize_base_url(os.environ.get("CONCERT_URL", ""))
    api_key = os.environ.get("CONCERT_API_KEY", "").strip()
    if not api_key:
        raise ConcertError(
            "CONCERT_API_KEY is not set. Generate a Concert API key and export it. "
            "This script does not use the internal handle_login JWT flow."
        )

    hub_namespace = os.environ.get("CONCERT_HUB_NS", "concert-hub").strip()
    instance_id = os.environ.get("CONCERT_INSTANCE_ID", "").strip()
    if not instance_id:
        instance_id = discover_instance_id(hub_namespace)
    if not instance_id:
        raise ConcertError(
            "CONCERT_INSTANCE_ID is not set and could not be discovered with oc. "
            "Export the instance ID displayed when the Concert API key was generated."
        )

    environment_override = (
        args.env_name.strip()
        if args.env_name is not None
        else os.environ.get("CONCERT_ENV_NAME", "").strip()
    )
    request_timeout = positive_int(
        os.environ.get("CONCERT_REQUEST_TIMEOUT", "60"),
        "CONCERT_REQUEST_TIMEOUT",
    )
    poll_timeout_raw = (
        str(args.poll_timeout)
        if args.poll_timeout is not None
        else os.environ.get("CONCERT_POLL_TIMEOUT", "300")
    )
    poll_interval_raw = (
        str(args.poll_interval)
        if args.poll_interval is not None
        else os.environ.get("CONCERT_POLL_INTERVAL", "5")
    )
    poll_timeout = positive_int(
        poll_timeout_raw,
        "CONCERT_POLL_TIMEOUT",
        allow_zero=True,
    )
    poll_interval = positive_int(
        poll_interval_raw,
        "CONCERT_POLL_INTERVAL",
    )

    ca_bundle = os.environ.get("CONCERT_CA_BUNDLE", "").strip()
    if ca_bundle and not Path(ca_bundle).is_file():
        raise ConcertError(f"CONCERT_CA_BUNDLE does not exist: {ca_bundle}")

    return Config(
        base_url=base_url,
        api_key=api_key,
        instance_id=instance_id,
        environment_override=environment_override,
        hub_namespace=hub_namespace,
        request_timeout=request_timeout,
        poll_timeout=poll_timeout,
        poll_interval=poll_interval,
        skip_tls=env_bool("CONCERT_SKIP_TLS", False),
        ca_bundle=ca_bundle,
        check_environment=not args.skip_environment_check,
    )


def make_ssl_context(config: Config) -> ssl.SSLContext:
    context = ssl.create_default_context()
    if config.ca_bundle:
        context.load_verify_locations(cafile=config.ca_bundle)
    if config.skip_tls:
        context.check_hostname = False
        context.verify_mode = ssl.CERT_NONE
    return context


def request(
    method: str,
    url: str,
    headers: Mapping[str, str],
    config: Config,
    data: Optional[bytes] = None,
) -> HttpResult:
    req = urllib.request.Request(url, data=data, headers=dict(headers), method=method)
    try:
        with urllib.request.urlopen(
            req,
            context=make_ssl_context(config),
            timeout=config.request_timeout,
        ) as response:
            return HttpResult(
                status=response.status,
                body=response.read(),
                headers=dict(response.headers.items()),
            )
    except urllib.error.HTTPError as exc:
        try:
            body = exc.read()
        except OSError:
            body = b""
        return HttpResult(
            status=exc.code,
            body=body,
            headers=dict(exc.headers.items()) if exc.headers else {},
        )
    except urllib.error.URLError as exc:
        reason = getattr(exc, "reason", exc)
        raise ConcertError(f"Request failed for {url}: {reason}") from exc
    except TimeoutError as exc:
        raise ConcertError(
            f"Request timed out after {config.request_timeout}s: {url}"
        ) from exc


def api_headers(config: Config, accept: str = "application/json") -> Dict[str, str]:
    return {
        "Authorization": config.authorization_header,
        "InstanceID": config.instance_id,
        "Accept": accept,
    }


def response_summary(result: HttpResult, limit: int = 1200) -> str:
    parsed = result.json_or_none()
    if parsed is not None:
        text = json.dumps(parsed, indent=2, sort_keys=True)
    else:
        text = result.text.strip()
    if not text:
        return "<empty response>"
    return text if len(text) <= limit else f"{text[:limit]}..."


def extract_collection(body: Any, preferred_key: str) -> List[Dict[str, Any]]:
    if isinstance(body, list):
        return [item for item in body if isinstance(item, dict)]
    if not isinstance(body, dict):
        return []

    preferred = body.get(preferred_key)
    if isinstance(preferred, list):
        return [item for item in preferred if isinstance(item, dict)]

    for key in ("items", "results", "resources"):
        value = body.get(key)
        if isinstance(value, list):
            return [item for item in value if isinstance(item, dict)]

    nested = body.get("data")
    if isinstance(nested, dict):
        return extract_collection(nested, preferred_key)
    if isinstance(nested, list):
        return [item for item in nested if isinstance(item, dict)]
    return []


def load_csv(path: Path, environment_override: str) -> CsvInput:
    if not path.is_file():
        raise ConcertError(f"Certificate CSV does not exist: {path}")

    try:
        handle = path.open("r", newline="", encoding="utf-8-sig")
    except OSError as exc:
        raise ConcertError(f"Cannot open certificate CSV {path}: {exc}") from exc

    with handle:
        reader = csv.DictReader(handle)
        original_fieldnames = reader.fieldnames or []
        fieldnames = [field.strip() if field else "" for field in original_fieldnames]
        reader.fieldnames = fieldnames

        if not fieldnames or any(not field for field in fieldnames):
            raise ConcertError("The certificate CSV has an empty or invalid header.")
        if len(fieldnames) != len(set(fieldnames)):
            raise ConcertError("The certificate CSV contains duplicate column names.")

        missing = [
            column for column in CERTIFICATE_REQUIRED_COLUMNS if column not in fieldnames
        ]
        if missing:
            raise ConcertError(
                "The certificate CSV is missing required columns: "
                + ", ".join(missing)
            )

        has_environment_column = "Environment" in fieldnames
        if not environment_override and not has_environment_column:
            raise ConcertError(
                "No Concert environment was specified. Set CONCERT_ENV_NAME or use "
                "--env-name. The certificate Namespace column is not automatically "
                "used as the Concert environment."
            )

        upload_fieldnames = [name for name in fieldnames if name != "Environment"]
        groups: Dict[str, List[Dict[str, str]]] = {}
        serials: Dict[str, Set[str]] = {}
        row_count = 0

        for line_number, raw_row in enumerate(reader, start=2):
            if None in raw_row:
                raise ConcertError(
                    f"CSV row {line_number} has more fields than the header. "
                    "Check quoting and embedded commas."
                )

            row = {
                str(key): (value if value is not None else "")
                for key, value in raw_row.items()
            }
            if not any(value.strip() for value in row.values()):
                continue

            environment = environment_override or row.get("Environment", "").strip()
            if not environment:
                raise ConcertError(
                    f"CSV row {line_number} has no Environment value and no "
                    "CONCERT_ENV_NAME/--env-name override was supplied."
                )

            serial = row.get("Serial Number", "").strip()
            if not serial:
                raise ConcertError(f"CSV row {line_number} has an empty Serial Number.")

            normalized = normalize_serial(serial)
            if normalized in serials.setdefault(environment, set()):
                raise ConcertError(
                    f"Duplicate certificate serial {serial!r} in environment "
                    f"{environment!r}."
                )

            serials[environment].add(normalized)
            groups.setdefault(environment, []).append(row)
            row_count += 1

    if row_count == 0:
        raise ConcertError("The certificate CSV contains no data rows.")

    return CsvInput(
        fieldnames=fieldnames,
        upload_fieldnames=upload_fieldnames,
        groups=groups,
        serials=serials,
        row_count=row_count,
    )


def normalize_serial(value: Any) -> str:
    text = str(value or "").strip().upper()
    compact = "".join(character for character in text if character not in {":", "-", " "})
    return compact.lstrip("0") or "0"


def list_visible_environments(config: Config) -> Set[str]:
    url = f"{config.base_url}{ENVIRONMENTS_PATH}"
    result = request("GET", url, api_headers(config), config)
    if result.status != 200:
        raise ConcertError(
            f"Environment preflight returned HTTP {result.status}.\n"
            f"{response_summary(result)}"
        )

    environments = extract_collection(result.json_or_none(), "environments")
    return {
        str(item.get("name", "")).strip()
        for item in environments
        if str(item.get("name", "")).strip()
    }


def ensure_environments_visible(config: Config, required: Iterable[str]) -> None:
    required_names = set(required)
    visible = list_visible_environments(config)
    missing = sorted(required_names - visible)
    if missing:
        available = ", ".join(sorted(visible)) if visible else "<none visible>"
        raise ConcertError(
            "The following Concert environment(s) do not exist or are not visible "
            f"to this API key: {', '.join(missing)}.\n"
            f"Visible environments: {available}\n"
            "Create the environment and grant the API-key owner access before uploading."
        )


def encode_multipart(
    fields: Sequence[Tuple[str, str]],
    file_field: str,
    filename: str,
    content: bytes,
    content_type: str,
) -> Tuple[bytes, str]:
    boundary = f"----concert-{uuid.uuid4().hex}"
    output = io.BytesIO()

    for name, value in fields:
        output.write(f"--{boundary}\r\n".encode("utf-8"))
        output.write(
            f'Content-Disposition: form-data; name="{name}"\r\n\r\n'.encode(
                "utf-8"
            )
        )
        output.write(value.encode("utf-8"))
        output.write(b"\r\n")

    safe_filename = filename.replace('"', "_")
    output.write(f"--{boundary}\r\n".encode("utf-8"))
    output.write(
        (
            f'Content-Disposition: form-data; name="{file_field}"; '
            f'filename="{safe_filename}"\r\n'
        ).encode("utf-8")
    )
    output.write(f"Content-Type: {content_type}\r\n\r\n".encode("utf-8"))
    output.write(content)
    output.write(b"\r\n")
    output.write(f"--{boundary}--\r\n".encode("utf-8"))

    return output.getvalue(), f"multipart/form-data; boundary={boundary}"


def build_group_csv(csv_input: CsvInput, rows: Sequence[Dict[str, str]]) -> bytes:
    output = io.StringIO(newline="")
    writer = csv.DictWriter(
        output,
        fieldnames=csv_input.upload_fieldnames,
        extrasaction="ignore",
        lineterminator="\r\n",
    )
    writer.writeheader()
    writer.writerows(rows)
    return output.getvalue().encode("utf-8")


def upload_group(
    config: Config,
    environment: str,
    filename: str,
    csv_content: bytes,
) -> HttpResult:
    metadata = json.dumps({"env_name": environment}, separators=(",", ":"))
    body, content_type = encode_multipart(
        fields=(("data_type", "certificate"), ("metadata", metadata)),
        file_field="filename",
        filename=filename,
        content=csv_content,
        content_type="text/csv",
    )
    headers = api_headers(config)
    headers["Content-Type"] = content_type
    return request(
        "POST",
        f"{config.base_url}{UPLOAD_PATH}",
        headers,
        config,
        data=body,
    )


def extract_tracking_details(result: HttpResult) -> Tuple[List[str], List[str]]:
    body = result.json_or_none()
    if not isinstance(body, dict):
        return [], []
    event_ids = body.get("event_ids")
    record_paths = body.get("record_paths")
    return (
        [str(value) for value in event_ids] if isinstance(event_ids, list) else [],
        [str(value) for value in record_paths]
        if isinstance(record_paths, list)
        else [],
    )


def fetch_certificate_serials(config: Config) -> Tuple[int, Set[str], str]:
    result = request(
        "GET",
        f"{config.base_url}{CERTIFICATES_PATH}",
        api_headers(config),
        config,
    )
    if result.status != 200:
        return result.status, set(), response_summary(result)

    certificates = extract_collection(result.json_or_none(), "certificates")
    serials: Set[str] = set()
    for item in certificates:
        raw_serial = (
            item.get("serial_number")
            or item.get("serialNumber")
            or item.get("Serial Number")
            or ""
        )
        if str(raw_serial).strip():
            serials.add(normalize_serial(raw_serial))
    return result.status, serials, ""


def poll_for_serials(
    config: Config,
    expected: Set[str],
) -> PollResult:
    if config.poll_timeout == 0:
        return PollResult(
            confirmed=False,
            found=set(),
            missing=set(expected),
            last_http_status=0,
        )

    deadline = time.monotonic() + config.poll_timeout
    attempt = 0
    last_status = 0
    found: Set[str] = set()
    last_error = ""

    while True:
        attempt += 1
        try:
            status, visible, error_text = fetch_certificate_serials(config)
        except ConcertError as exc:
            status, visible, error_text = 0, set(), str(exc)

        last_status = status
        last_error = error_text
        found = expected & visible
        missing = expected - visible
        remaining = max(0, int(deadline - time.monotonic()))
        print(
            f"      poll {attempt:>2}: HTTP {status or '-'}; "
            f"confirmed {len(found)}/{len(expected)}; {remaining}s remaining"
        )

        if not missing and status == 200:
            return PollResult(True, found, set(), status)

        if status in {401, 403}:
            return PollResult(
                confirmed=False,
                found=found,
                missing=missing,
                last_http_status=status,
                fatal_error=(
                    f"Certificate verification was denied with HTTP {status}: "
                    f"{last_error}"
                ),
            )

        now = time.monotonic()
        if now >= deadline:
            return PollResult(
                confirmed=False,
                found=found,
                missing=missing,
                last_http_status=last_status,
                fatal_error="",
            )

        time.sleep(min(config.poll_interval, max(0.0, deadline - now)))


def safe_environment_filename(environment: str) -> str:
    safe = "".join(
        character if character.isalnum() or character in {"-", "_"} else "_"
        for character in environment
    ).strip("_")
    return safe or "environment"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Upload and verify IBM Concert certificate inventory CSV data."
    )
    parser.add_argument(
        "csv_file",
        nargs="?",
        default="concert-certificates.csv",
        help="Certificate CSV file (default: concert-certificates.csv).",
    )
    parser.add_argument(
        "--env-name",
        help=(
            "Concert environment for every row. Overrides CONCERT_ENV_NAME and "
            "an optional CSV Environment column."
        ),
    )
    parser.add_argument(
        "--poll-timeout",
        type=int,
        help="Seconds to wait for records; 0 disables waiting and returns exit code 2.",
    )
    parser.add_argument(
        "--poll-interval",
        type=int,
        help="Seconds between certificate verification requests.",
    )
    parser.add_argument(
        "--skip-environment-check",
        action="store_true",
        help="Skip the preflight check that the target environment is visible.",
    )
    return parser


def print_banner(config: Config, csv_path: Path) -> None:
    print("=" * 68)
    print("  IBM Concert 3.0.x - Certificate Upload")
    print("=" * 68)
    print(f"  Concert API base : {config.base_url}")
    print(f"  CSV file         : {csv_path}")
    print("  Authentication   : C_API_KEY")
    print(f"  Instance ID      : {config.instance_id}")
    print(
        f"  Environment      : {config.environment_override or 'CSV Environment column'}"
    )
    print(f"  Environment check: {'enabled' if config.check_environment else 'skipped'}")
    print(f"  TLS verification : {'DISABLED' if config.skip_tls else 'enabled'}")
    print(
        f"  Polling          : {config.poll_timeout}s timeout / "
        f"{config.poll_interval}s interval"
    )
    print("=" * 68)
    if config.skip_tls:
        print("WARNING: CONCERT_SKIP_TLS=true disables certificate verification.")
        print("         Use CONCERT_CA_BUNDLE for non-disposable environments.")
        print()


def run(args: argparse.Namespace) -> int:
    config = build_config(args)
    csv_path = Path(args.csv_file).expanduser()
    csv_input = load_csv(csv_path, config.environment_override)
    print_banner(config, csv_path)

    print(
        f"Read {csv_input.row_count} certificate row(s) across "
        f"{len(csv_input.groups)} environment(s): "
        f"{', '.join(csv_input.groups)}"
    )
    print()

    if config.check_environment:
        print("Checking that target environments exist and are visible...")
        ensure_environments_visible(config, csv_input.groups.keys())
        print("Environment preflight passed.")
        print()

    accepted = 0
    confirmed = 0
    pending = 0
    failed = 0
    all_event_ids: List[str] = []

    for index, (environment, rows) in enumerate(csv_input.groups.items(), start=1):
        print("-" * 68)
        print(
            f"[{index}/{len(csv_input.groups)}] Environment {environment!r}: "
            f"{len(rows)} certificate(s)"
        )
        filename = f"certificates-{safe_environment_filename(environment)}.csv"
        content = build_group_csv(csv_input, rows)
        print(f"Uploading {filename} ({len(content)} bytes)...")

        try:
            result = upload_group(config, environment, filename, content)
        except ConcertError as exc:
            print(f"ERROR: {exc}")
            failed += 1
            continue

        if result.status not in {200, 201, 202}:
            print(f"ERROR: upload returned HTTP {result.status}.")
            print(response_summary(result))
            failed += 1
            continue

        accepted += 1
        print(f"Upload accepted with HTTP {result.status}.")
        event_ids, record_paths = extract_tracking_details(result)
        all_event_ids.extend(event_ids)
        for event_id in event_ids:
            print(f"  Event ID   : {event_id}")
        for record_path in record_paths:
            print(f"  Record path: {record_path}")

        print("Waiting for certificate records to become visible...")
        outcome = poll_for_serials(config, csv_input.serials[environment])

        if outcome.confirmed:
            print(
                f"CONFIRMED: all {len(outcome.found)} certificate(s) are visible."
            )
            confirmed += 1
        elif outcome.fatal_error:
            print(f"ERROR: {outcome.fatal_error}")
            failed += 1
        else:
            missing_display = ", ".join(sorted(outcome.missing)[:5])
            suffix = "..." if len(outcome.missing) > 5 else ""
            print(
                f"PENDING: {len(outcome.missing)} certificate(s) were not visible "
                f"after {config.poll_timeout}s."
            )
            if missing_display:
                print(f"  Missing serials: {missing_display}{suffix}")
            if event_ids:
                print("  Search the Concert Event log using the Event ID shown above.")
            pending += 1

    print()
    print("=" * 68)
    print("  Summary")
    print("=" * 68)
    print(f"  Certificate rows : {csv_input.row_count}")
    print(f"  Upload groups    : {len(csv_input.groups)}")
    print(f"  Accepted         : {accepted}")
    print(f"  Confirmed        : {confirmed}")
    print(f"  Pending          : {pending}")
    print(f"  Failed           : {failed}")
    if all_event_ids:
        print(f"  Event IDs        : {', '.join(all_event_ids)}")
    print("=" * 68)

    if failed:
        print("One or more certificate uploads or verification requests failed.")
        return 1
    if pending:
        print(
            "Every upload was accepted, but at least one import remains unconfirmed."
        )
        return 2

    print("All certificate uploads were accepted and confirmed in Concert.")
    return 0


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    try:
        return run(args)
    except ConcertError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("Interrupted.", file=sys.stderr)
        return 130


if __name__ == "__main__":
    sys.exit(main())
